from typing import Protocol


class Environment(Protocol):
    """A pure single-world environment with explicit state and parameters."""

    @property
    def spec(self): ...

    def default_params(self): ...

    def reset(self, key, params): ...

    def step(self, key, state, actions, params): ...

    def observe(self, state, params): ...

    def global_state(self, state, params): ...


class Model(Protocol):
    """A function representation with explicit variables and inference carry."""

    def init(self, key, input_spec, output_spec): ...

    def initial_carry(self): ...

    def apply(self, variables, inputs, carry, key): ...


class Method(Protocol):
    """A learning rule with explicit training state and a frozen-policy output."""

    def init(self, key, agent, spec): ...

    def update(self, state, batch, key): ...

    def freeze(self, state): ...
